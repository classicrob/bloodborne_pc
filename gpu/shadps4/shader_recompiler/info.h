enum class Qualifier : u8 {
    None,
    Smooth,
    NoPerspective,
    PerVertex,
    Flat,
    Centroid,
    Sample,
};

/**
 * Contains general information generated by the shader recompiler for an input program.
 */
struct InfoPersistent {
    struct AttributeFlags {
        bool Get(IR::Attribute attrib, u32 comp = 0) const {
            return flags[Index(attrib)] & (1 << comp);
        }

        bool GetAny(IR::Attribute attrib) const {
            return flags[Index(attrib)];
        }

        void Set(IR::Attribute attrib, u32 comp = 0) {
            flags[Index(attrib)] |= (1 << comp);
        }

        u32 NumComponents(IR::Attribute attrib) const {
            return 4;
        }

        static size_t Index(IR::Attribute attrib) {
            return static_cast<size_t>(attrib);
        }

        std::array<u8, IR::NumAttributes> flags;
    };

    /// bbport: in the persistent part, so a stage rebuilt from the pipeline cache still knows
    /// which attributes it reads and writes (Apple pre-raster/fragment interface, layer and
    /// clip-distance checks).
    AttributeFlags loads{};
    AttributeFlags stores{};

    struct Interpolation {
        Qualifier primary;
        Qualifier auxiliary;
    };
    /// bbport: persistent as well, so a pipeline rebuilt from the cache is checked against the
    /// fragment inputs it declares (Apple RectList/QuadList flat inputs).
    std::array<Interpolation, IR::NumParams> fs_interpolation{};

    BufferResourceList buffers;
    ImageResourceList images;
    SamplerResourceList samplers;
    FMaskResourceList fmasks;
#ifdef __APPLE__
    u32 depth_bounds_binding{std::numeric_limits<u32>::max()};
#endif

    struct UserDataMask {
        void Set(IR::ScalarReg reg) noexcept {
            mask |= 1 << static_cast<u32>(reg);
        }

        u32 Index(IR::ScalarReg reg) const noexcept {
            const u32 reg_mask = (1 << static_cast<u32>(reg)) - 1;
            return std::popcount(mask & reg_mask);
        }

        u32 NumRegs() const noexcept {
            return std::popcount(mask);
        }

        u32 mask;
    };
    UserDataMask ud_mask{};
    u32 fetch_shader_sgpr_base{};
    u32 shared_memory_scratch_size{};

    u64 pgm_hash{};

    s32 tess_consts_dword_offset = -1;
    IR::ScalarReg tess_consts_ptr_base = IR::ScalarReg::Max;
    HwStage hw_stage;
    SwStage sw_stage;

    u8 mrt_mask{};
    bool has_fetch_shader{};
    bool has_bitwise_xor{};
    bool uses_dma{};

    InfoPersistent() = default;
    InfoPersistent(HwStage hw_stage_, SwStage sw_stage_, u64 pgm_hash_)
        : hw_stage{hw_stage_}, sw_stage{sw_stage_}, pgm_hash{pgm_hash_} {}
};

struct Info : InfoPersistent {
    enum class ReadConstType {
        None = 0,
        Immediate = 1 << 0,
        Dynamic = 1 << 1,
    };

    std::span<const u32> user_data;
    std::vector<u32> flattened_ud_buf;
    PersistentSrtInfo srt_info;

    ReadConstType readconst_types{};
    CopyShaderData gs_copy_data;
    u32 uses_patches{};

    VAddr pgm_base;
    bool has_storage_images{};
    bool has_discard{};
    bool has_image_gather{};
    bool has_image_query{};
    bool has_readconst{};
    bool uses_buffer_atomic_float_min_max{};
    bool uses_image_atomic_float_min_max{};
    bool uses_lane_id{};
    bool uses_shader_clock{};
    bool uses_group_quad{};
    bool uses_group_shuffle{};
    bool uses_group_ballot{};
    bool uses_group_arithmetic{};
    IR::Type shared_types{};
    bool uses_fp16{};
    bool uses_fp64{};
    bool uses_pack_10_11_11{};
    bool uses_unpack_10_11_11{};
    bool uses_buffer_int64_atomics{};
    bool uses_shared_int64_atomics{};
    bool stores_tess_level_outer{};
    bool stores_tess_level_inner{};
    bool translation_failed{};

    Info() = default;
    Info(HwStage stage_, SwStage l_stage_, ShaderParams params)
        : InfoPersistent(stage_, l_stage_, params.hash), pgm_base{params.Base()},
          user_data{params.user_data} {}

    /// bbport: user data of this stage as a draw saw it. The GPU command thread refreshes
    /// user_data/flattened_ud_buf for every draw it decodes, while the draw recording thread
    /// (vk_draw_pipe.h) may still work on an earlier draw: that thread installs snapshots here.
    struct UdSnapshot {
        const Info* info;
        const u32* user_data;
        u32 user_data_size;
        const u32* flat;
        u32 flat_size;
        VAddr pgm_base;
    };
    static constexpr u32 MaxUdSnapshots = 6;
    static inline thread_local UdSnapshot ud_snapshots[MaxUdSnapshots];
    static inline thread_local u32 num_ud_snapshots = 0;

    const UdSnapshot* Snapshot() const noexcept {
        // A temporary specialization view can shadow a draw-packet snapshot on this thread.
        for (u32 i = num_ud_snapshots; i > 0; --i) {
            if (ud_snapshots[i - 1].info == this) {
                return &ud_snapshots[i - 1];
            }
        }
        return nullptr;
    }
    std::span<const u32> UserData() const noexcept {
        if (const auto* snapshot = Snapshot()) [[unlikely]] {
            return {snapshot->user_data, snapshot->user_data_size};
        }
        return user_data;
    }
    std::span<const u32> FlatUserData() const noexcept {
        if (const auto* snapshot = Snapshot()) [[unlikely]] {
            return {snapshot->flat, snapshot->flat_size};
        }
        return flattened_ud_buf;
    }

    VAddr ProgramBase() const noexcept {
        if (const auto* snapshot = Snapshot()) [[unlikely]] {
            return snapshot->pgm_base;
        }
        return pgm_base;
    }

    template <typename T>
    inline T ReadUdSharp(u32 sharp_idx) const noexcept {
        return *reinterpret_cast<const T*>(&FlatUserData()[sharp_idx]);
    }

    template <typename T>
    T ReadUdReg(u32 ptr_index, u32 dword_offset) const noexcept {
        T data;
        const auto ud = UserData();
        const u32* base = ud.data();
        if (ptr_index != IR::NumScalarRegs) {
            std::memcpy(&base, &ud[ptr_index], sizeof(base));
            base = reinterpret_cast<const u32*>(VAddr(base) & 0xFFFFFFFFFFFFULL);
        }
        std::memcpy(&data, base + dword_offset, sizeof(T));
#ifdef __APPLE__
        // A read through a user-data pointer (a descriptor table): where it lies relative to
        // the submitted command memory (BB_CMD_DATA_CHECK).
        if (ptr_index != IR::NumScalarRegs && BbCmdData::Enabled()) [[unlikely]] {
            BbCmdData::NoteRead("ud table", pgm_hash, base + dword_offset, sizeof(T), &data,
                                &ud[ptr_index]);
        }
#endif
        return data;
    }

    void PushUd(Backend::Bindings& bnd, PushData& push) const {
        const auto ud = UserData();
        u32 mask = ud_mask.mask;
        while (mask) {
            const u32 index = std::countr_zero(mask);
            ASSERT_MSG(bnd.user_data < NUM_PUSH_USER_DATA_REGS && index < NUM_USER_DATA_REGS,
                       "pipeline user data exceeds the push block: slot {} of {}, SGPR {}",
                       bnd.user_data, NUM_PUSH_USER_DATA_REGS, index);
            mask &= ~(1U << index);
            push.ud_regs[bnd.user_data++] = ud[index];
        }
    }

    /// The bindings a stored permutation takes (cache hits and preloads; a compiled stage
    /// advances them itself): an image takes its permutation's descriptor count.
    void AddBindings(Backend::Bindings& bnd) const {
        bnd.buffer += buffers.size();
        u32 image_bindings = 0;
        for (const auto& image : images) {
            ASSERT_MSG(image.permutation_bindings,
                       "Image of shader {:#x} has no recorded binding count", pgm_hash);
            image_bindings += image.permutation_bindings;
        }
        bnd.unified += buffers.size() + image_bindings + samplers.size();
        bnd.user_data += ud_mask.NumRegs();
    }

    void RefreshFlatBuf() {
        RefreshFlatBuf(user_data, flattened_ud_buf);
    }

    void InitFlatBuf(std::span<const u32> data, std::vector<u32>& flat) const {
        flat.resize(srt_info.flattened_bufsize_dw);
        ASSERT(data.size() <= NUM_USER_DATA_REGS);
        std::memcpy(flat.data(), data.data(), data.size_bytes());
    }

    void RefreshFlatBuf(std::span<const u32> data, std::vector<u32>& flat) const {
        InitFlatBuf(data, flat);
        if (srt_info.walker_func) {
            srt_info.walker_func(data.data(), flat.data());
        }
    }

    void ReadTessConstantBuffer(TessellationDataConstantBuffer& tess_constants) const {
        ASSERT(tess_consts_dword_offset >= 0); // We've already tracked the V# UD
        auto buf = ReadUdReg<AmdGpu::Buffer>(static_cast<u32>(tess_consts_ptr_base),
                                             static_cast<u32>(tess_consts_dword_offset));
        VAddr tess_constants_addr = buf.base_address;
        memcpy(&tess_constants,
               reinterpret_cast<TessellationDataConstantBuffer*>(tess_constants_addr),
               sizeof(tess_constants));
#ifdef __APPLE__
        if (BbCmdData::Enabled()) [[unlikely]] {
            BbCmdData::NoteRead("tess constants", pgm_hash,
                                reinterpret_cast<const void*>(tess_constants_addr),
                                sizeof(tess_constants), &tess_constants);
        }
#endif
    }

    void Serialize(Serialization::Archive& ar) const;
    bool Deserialize(Serialization::Archive& ar);
};
